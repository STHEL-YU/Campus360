export async function createStudentRegistration({
  fullName,
  schoolId,
  email,
  college,
  program,
  yearLevel,
  passwordHash,
  role,
  schoolIdImagePath,
}) {
  await ensureStudentsTable();

  const result = await query(
    `INSERT INTO students
      (full_name, school_id, email, college, program, year_level, password_hash, role, status, school_id_image_path)
     VALUES ($1, $2, $3, $4, $5, $6, $7, $8, 'pending', $9)
     RETURNING id, full_name, email, role, status`,
    [
      fullName,
      schoolId,
      email,
      college,
      program,
      yearLevel,
      passwordHash,
      role,
      schoolIdImagePath,
    ],
  );

  return result.rows[0];
}

export async function findStudentForLogin(identifier) {
  await ensureStudentsTable();

  const result = await query(
    `SELECT id, full_name, school_id, email, college, program, year_level,
            profile_image_path, role, status, password_hash
     FROM public.students
     WHERE LOWER(email) = LOWER($1) OR LOWER(school_id) = LOWER($1)
     ORDER BY CASE WHEN LOWER(email) = LOWER($1) THEN 0 ELSE 1 END
     LIMIT 1`,
    [identifier],
  );

  return result.rows[0] || null;
}

