export async function findOrLinkAdminByGoogleIdentity(googleSub, email) {
  await ensureAdminsTable();

  const existing = await findAdminByGoogleSub(googleSub);
  if (existing) {
    return existing;
  }

  const linked = await query(
    `UPDATE public.admins
     SET google_sub = $1
     WHERE LOWER(email) = LOWER($2) AND google_sub IS NULL
     RETURNING id, first_name, middle_name, last_name, email, phone, employee_id, college, status, created_at`,
    [googleSub, email],
  );
  if (linked.rows[0]) {
    return linked.rows[0];
  }

  return findAdminByGoogleSub(googleSub);
}

