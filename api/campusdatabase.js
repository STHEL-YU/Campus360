export async function updateStudentForAdmin(id, updates, college) {
  await ensureStudentsTable();

  const columns = {
    fullName: "full_name",
    schoolId: "school_id",
    email: "email",
    college: "college",
    program: "program",
    yearLevel: "year_level",
    role: "role",
    status: "status",
  };
  const entries = Object.entries(columns).filter(([key]) =>
    Object.prototype.hasOwnProperty.call(updates, key),
  );
  if (entries.length === 0) {
    return null;
  }

  const values = entries.map(([key]) => updates[key]);
  const assignments = entries.map(
    ([key], index) => `${columns[key]} = $${index + 1}`,
  );
  values.push(id, college);

  const result = await query(
    `UPDATE public.students
     SET ${assignments.join(", ")}
     WHERE id = $${values.length - 1} AND college = $${values.length}
     RETURNING id, full_name, school_id, email, college, program, year_level, role, status, created_at`,
    values,
  );

  return result.rows[0] || null;
}

