import dotenv from "dotenv";
import pg from "pg";
import process from "node:process";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
dotenv.config({ path: path.join(__dirname, "../.env.local") });

const { Pool } = pg;

if (!process.env.DATABASE_URL) {
  throw new Error("DATABASE_URL is not configured");
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: { rejectUnauthorized: false },
});

let schemaPromise;
let adminSchemaPromise;
let newsSchemaPromise;
let incidentReportSchemaPromise;

export function query(text, params) {
  return pool.query(text, params);
}

async function ensureStudentsTable() {
  if (!schemaPromise) {
    schemaPromise = (async () => {
      await query(`
        CREATE TABLE IF NOT EXISTS public.students (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          full_name TEXT NOT NULL,
          school_id TEXT NOT NULL UNIQUE,
          email TEXT NOT NULL UNIQUE,
          college TEXT NOT NULL,
          program TEXT NOT NULL,
          year_level TEXT NOT NULL,
          password_hash TEXT NOT NULL,
          role TEXT NOT NULL CHECK (role IN ('Student', 'Faculty')),
          status TEXT NOT NULL DEFAULT 'pending',
          school_id_image_path TEXT NOT NULL,
          profile_image_path TEXT,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
      `);
      await query(
        "ALTER TABLE public.students ADD COLUMN IF NOT EXISTS profile_image_path TEXT",
      );
    })().catch((error) => {
      schemaPromise = undefined;
      throw error;
    });
  }

  await schemaPromise;
}

async function ensureAdminsTable() {
  if (!adminSchemaPromise) {
    adminSchemaPromise = (async () => {
      await query(`
        CREATE TABLE IF NOT EXISTS public.admins (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          first_name TEXT NOT NULL,
          middle_name TEXT,
          last_name TEXT NOT NULL,
          email TEXT NOT NULL UNIQUE,
          google_sub TEXT UNIQUE,
          phone TEXT NOT NULL,
          employee_id TEXT NOT NULL UNIQUE,
          college TEXT NOT NULL,
          status TEXT NOT NULL DEFAULT 'active',
          password_hash TEXT,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
      `);
      await query(
        "ALTER TABLE public.admins ALTER COLUMN google_sub DROP NOT NULL",
      );
      await query(
        "ALTER TABLE public.admins ADD COLUMN IF NOT EXISTS password_hash TEXT",
      );
      await query(
        "ALTER TABLE public.admins ALTER COLUMN status SET DEFAULT 'active'",
      );
      await query(
        "UPDATE public.admins SET status = 'active' WHERE LOWER(status) = 'pending'",
      );
    })().catch((error) => {
      adminSchemaPromise = undefined;
      throw error;
    });
  }

  await adminSchemaPromise;
}

async function ensureIncidentReportsTable() {
  if (!incidentReportSchemaPromise) {
    incidentReportSchemaPromise = (async () => {
      await ensureStudentsTable();
      await query(`
        CREATE TABLE IF NOT EXISTS public.incident_reports (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          student_id BIGINT REFERENCES public.students(id) ON DELETE SET NULL,
          category TEXT NOT NULL,
          college TEXT NOT NULL,
          building TEXT NOT NULL,
          location TEXT NOT NULL DEFAULT '',
          description TEXT NOT NULL DEFAULT '',
          pin_x NUMERIC(5, 2),
          pin_y NUMERIC(5, 2),
          image_path TEXT,
          audio_path TEXT,
          is_anonymous BOOLEAN NOT NULL DEFAULT TRUE,
          status TEXT NOT NULL DEFAULT 'New',
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          CHECK (
            (pin_x IS NULL AND pin_y IS NULL) OR
            (
              pin_x IS NOT NULL AND pin_y IS NOT NULL AND
              pin_x BETWEEN 0 AND 100 AND pin_y BETWEEN 0 AND 100
            )
          )
        )
      `);
      await query(`
        ALTER TABLE public.incident_reports
          ADD COLUMN IF NOT EXISTS image_path TEXT,
          ADD COLUMN IF NOT EXISTS audio_path TEXT,
          ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      `);
      await query(`
        CREATE INDEX IF NOT EXISTS incident_reports_student_created_idx
        ON public.incident_reports (student_id, created_at DESC)
      `);
    })().catch((error) => {
      incidentReportSchemaPromise = undefined;
      throw error;
    });
  }

  await incidentReportSchemaPromise;
}

async function ensureNewsTable() {
  if (!newsSchemaPromise) {
    newsSchemaPromise = query(`
      CREATE TABLE IF NOT EXISTS public.news_announcements (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        type TEXT NOT NULL,
        audience TEXT NOT NULL,
        content TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'Published',
        event_at TIMESTAMPTZ,
        target_college TEXT,
        image_path TEXT,
        image_url TEXT,
        published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `)
      .then(() =>
        query(`
        ALTER TABLE public.news_announcements
          ADD COLUMN IF NOT EXISTS event_at TIMESTAMPTZ,
          ADD COLUMN IF NOT EXISTS target_college TEXT,
          ADD COLUMN IF NOT EXISTS image_path TEXT,
          ADD COLUMN IF NOT EXISTS image_url TEXT
      `),
      )
      .catch((error) => {
        newsSchemaPromise = undefined;
        throw error;
      });
  }

  await newsSchemaPromise;
}

